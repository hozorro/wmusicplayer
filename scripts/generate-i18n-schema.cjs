const fs = require('fs')
const path = require('path')

const LANG_DIR = path.resolve(__dirname, '../src/i18n/langs')
const OUTPUT = path.resolve(__dirname, '../src/i18n/schema.d.ts')

function toTsType(obj, indent = 2) {
  const space = ' '.repeat(indent)
  let result = '{\n'

  for (const key in obj) {
    const value = obj[key]

    if (typeof value === 'object' && !Array.isArray(value)) {
      result += `${space}${key}: ${toTsType(value, indent + 2)}\n`
    } else {
      result += `${space}${key}: string\n`
    }
  }

  result += ' '.repeat(indent - 2) + '}'
  return result
}

function mergeObjects(target, source) {
  for (const key in source) {
    if (
      typeof source[key] === 'object' &&
      !Array.isArray(source[key]) &&
      typeof target[key] === 'object'
    ) {
      mergeObjects(target[key], source[key])
    } else {
      target[key] = source[key]
    }
  }
}

function generate() {
  const files = fs.readdirSync(LANG_DIR).filter(f => f.endsWith('.json'))

  let merged = {}

  for (const file of files) {
    const json = JSON.parse(fs.readFileSync(path.join(LANG_DIR, file), 'utf8'))
    mergeObjects(merged, json)
  }

  const schema = `
/* Auto-generated by generate-i18n-schema.cjs */

import { DefineLocaleMessage } from 'vue-i18n'

declare module 'vue-i18n' {
  export interface DefineLocaleMessage ${toTsType(merged)}
}
`

  fs.writeFileSync(OUTPUT, schema.trim() + '\n')
  console.log(`Generated: ${OUTPUT}`)
}

generate()
